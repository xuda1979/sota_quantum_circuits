F22_INV = [0, 1, 3, 2]   # GF(4), p = X^2+X+1, bit i = coeff of X^i
F23_INV = [0, 1, 5, 6, 7, 2, 3, 4]  # GF(8), p = X^3+X+1

F23_MONOS = [3, 5, 6, 7]
F23_IDX = {m: i for i, m in enumerate(F23_MONOS)}


def f23_d2(fn: int) -> int:
    f = [(fn >> x) & 1 for x in range(8)]
    for i in range(3):
        for m in range(8):
            if m >> i & 1:
                f[m] ^= f[m ^ (1 << i)]
    v = 0
    for m in range(1, 8):
        if f[m] and m in F23_IDX:
            v |= 1 << F23_IDX[m]
    return v


F23_XF = [sum(1 << x for x in range(8) if (x >> i) & 1) for i in range(3)]
F23_TGT = [sum(((F23_INV[x] >> b) & 1) << x for x in range(8))
           for b in range(3)]


def f23_T3_rank_argument() -> dict:
    """F23 T >= 3: rank span{d2(INV3_b)} = 3; recompute + menu check."""
    tgts = [f23_d2(t) for t in F23_TGT]
    basis: list[int] = []
    for v in tgts:
        w = v
        for b in basis:
            w = min(w, w ^ b)
        if w:
            basis.append(w)
            basis.sort(reverse=True)
    # products of x-affine pairs (complete no-ancilla first-op menu)
    forms = []
    for s in range(8):
        for c in (0, 1):
            t = 0xFF if c else 0
            for j in range(3):
                if s >> j & 1:
                    t ^= F23_XF[j]
            forms.append(t)
    zero = inside = outside = 0
    for i, a in enumerate(forms):
        for b in forms[i + 1:]:
            v = f23_d2(a & b)
            if v == 0:
                zero += 1
                continue
            w = v
            for bb in basis:
                w = min(w, w ^ bb)
            if w == 0:
                inside += 1
            else:
                outside += 1
    return {"rank_W": len(basis), "menu_d2_zero": zero,
            "menu_d2_inside_W": inside, "menu_d2_outside_W": outside,
            "T_ge_3_for_any_Q": len(basis) == 3}


