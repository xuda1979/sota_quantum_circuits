"""Optimality certificates for kickmix circuits.

A Certificate is a machine-checkable record that a given (T, Q) point is
optimal for a task within a precisely-stated circuit model. Structure:

  - task: name + reference (the function being computed),
  - construction: a valid circuit achieving (T*, Q*) [existence leg],
  - impossibility legs: for each (T', Q') strictly better on some axis,
    an exhaustive-search result showing no circuit in the model achieves
    it, WITH the model statement, node count, wall time, and the exact
    script + argv that reproduces the search,
  - verify(): re-runs the *cheap* algebraic checks (never the exhaustive
    search) and re-checks the construction's verdict, returning True iff
    everything still holds,
  - serialize()/deserialize to JSON.

Proven vs claimed discipline:
  - A leg is PROVEN only if `search_complete=True`: the search provably
    enumerates every circuit in `model` (completeness argument recorded
    in `completeness_note`).
  - Numbers (node counts, times) are recorded with the reproducing
    command; certificates are regenerated by run_all.sh, never edited
    by hand.
"""

from __future__ import annotations

