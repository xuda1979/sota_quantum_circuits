# ---------------------------------------------------------------------------
# F24 constants (GF(16), p(X) = X^4+X+1, little-endian bit packing)
# ---------------------------------------------------------------------------

F24_INV = [0, 1, 9, 14, 13, 11, 7, 6, 15, 2, 12, 5, 10, 4, 3, 8]

F24_MONOS = [m for m in range(1, 16) if bin(m).count("1") >= 2]
F24_IDX = {m: i for i, m in enumerate(F24_MONOS)}


def f24_d2(fn: int) -> int:
    """Degree>=2 ANF coordinate vector of a 4-var truth-table function."""
    f = [(fn >> x) & 1 for x in range(16)]
    for i in range(4):
        for m in range(16):
            if m >> i & 1:
                f[m] ^= f[m ^ (1 << i)]
    v = 0
    for m in range(1, 16):
        if f[m] and m in F24_IDX:
            v |= 1 << F24_IDX[m]
    return v


F24_XF = [sum(1 << x for x in range(16) if (x >> i) & 1) for i in range(4)]
F24_FULL = 0xFFFF
F24_TGT = [sum(((F24_INV[x] >> b) & 1) << x for x in range(16))
           for b in range(4)]
F24_TGT_D2 = [f24_d2(t) for t in F24_TGT]


# ---------------------------------------------------------------------------
# Cheap re-checkable algebraic facts (used by verify())
# ---------------------------------------------------------------------------

def f24_span_lower_bound_T() -> int:
    """dim of the span of the four target d2 vectors: any circuit needs at
    least this many products/Toffolis (each Toffoli adds one product whose
    d2 must cover the targets' d2 span). Cheap, exact."""
    basis: list[int] = []
    for v in F24_TGT_D2:
        w = v
        for b in basis:
            w = min(w, w ^ b)
        if w:
            basis.append(w)
            basis.sort(reverse=True)
    return len(basis)


def f24_bit0_needs_many_products() -> int:
    """Recompute the per-bit minimum number of menu products for bit 0 of
    F24 inversion (BFS to depth 4 over the 4-var product menu). Returns
    -1 if not reachable within 4 products (that IS the certificate fact).
    """
    # menu: d2 vectors of products of two affine 4-var forms
    menu: dict[int, bool] = {}
    forms = []
    for s in range(16):
        for c in (0, 1):
            t = F24_FULL if c else 0
            for j in range(4):
                if s >> j & 1:
                    t ^= F24_XF[j]
            forms.append(t)
    for i, a in enumerate(forms):
        for b in forms[i + 1:]:
            v = f24_d2(a & b)
            if v:
                menu.setdefault(v, True)
    tgt = F24_TGT_D2[0]
    if tgt in menu:
        return 1
    frontier = set(menu)
    if tgt in frontier:
        return 1
    for k in range(2, 5):
        nxt = {v ^ m for v in frontier for m in menu}
        if tgt in nxt:
            return k
        frontier |= nxt
    return -1  # not reachable with <= 4 products


def f24_T5_rank_argument() -> dict:
    """The strengthened T>=5 leg: rank proof valid for ANY qubit count Q
    (with h-bits allowed as operand sources).

    Facts (all recomputed here, cheap):
      1. rank of span{TGT_D2} = 4 (targets' degree>=2 content).
      2. No realizable x-affine-pair product has nonzero d2 inside W :=
         span{TGT_D2} (checked over the complete 171-product first-op
         menu; 31 have d2 = 0, 140 outside W, 0 inside).
      3. Products involving h-bits as operands have d2 = 0 or nonzero
         h-cross coordinates (W is x-only), so they cannot lie in W
         either (8-var view).
    Argument: any 4-Toffoli circuit's four product d2s must span W
    (dim 4) exactly, forcing every product's d2 into W; but no
    realizable product has nonzero d2 in W and at most ... products
    with d2 = 0 contribute nothing. Contradiction => T >= 5 for any Q.
    """
    # fact 1
    basis: list[int] = []
    for v in F24_TGT_D2:
        w = v
        for b in basis:
            w = min(w, w ^ b)
        if w:
            basis.append(w)
            basis.sort(reverse=True)
    rank_W = len(basis)
    # fact 2: first-op menu = products of x-affine pairs (ancillas |0>,
    # const-shaped ancillas are x-affine too), deduped
    forms = []
    for s in range(16):
        for c in (0, 1):
            t = F24_FULL if c else 0
            for j in range(4):
                if s >> j & 1:
                    t ^= F24_XF[j]
            forms.append(t)
    zero = inside = outside = 0
    for i, a in enumerate(forms):
        for b in forms[i + 1:]:
            v = f24_d2(a & b)
            if v == 0:
                zero += 1
                continue
            w = v
            for bb in basis:
                w = min(w, w ^ bb)
            if w == 0:
                inside += 1
            else:
                outside += 1
    return {"rank_W": rank_W, "menu_d2_zero": zero,
            "menu_d2_inside_W": inside, "menu_d2_outside_W": outside,
            "T_ge_5_for_any_Q": rank_W == 4 and inside == 0}



# ---------------------------------------------------------------------------
# Certificate data model
# ---------------------------------------------------------------------------

@dataclass
class Leg:
    name: str                      # e.g. "Q>=10 at T=5 (one ancilla)"
    statement: str                 # precise mathematical statement
    model: str                     # precise model assumptions
    verdict: str                   # "IMPOSSIBLE" | "POSSIBLE" | "OPEN"
    search_complete: bool          # True iff enumeration covers the model
    completeness_note: str         # why the enumeration is complete
    nodes: Optional[int] = None    # search nodes explored
    seconds: Optional[float] = None
    reproduce_cmd: Optional[list[str]] = None  # exact argv
    run_date: Optional[str] = None


@dataclass
class Certificate:
    task: str
    construction_name: str
    construction_T: int
    construction_Q: int
    construction_verdict: str      # evaluator verdict line
    legs: list[Leg] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def conclusion(self) -> str:
        proven = [l for l in self.legs
                  if l.verdict == "IMPOSSIBLE" and l.search_complete]
        parts = [f"Task {self.task}: construction {self.construction_name} "
                 f"achieves (T={self.construction_T}, Q={self.construction_Q})."]
        for l in proven:
            nodes = f"{l.nodes} nodes" if l.nodes is not None else "? nodes"
            secs = f"{l.seconds:.0f}s" if l.seconds is not None else "?s"
            parts.append(f"  [PROVEN] {l.statement} ({l.model}) "
                         f"[{nodes}, {secs}]")
        open_legs = [l for l in self.legs
                     if l.verdict == "OPEN" or not l.search_complete]
        for l in open_legs:
            parts.append(f"  [MODEL-LIMITED] {l.statement} ({l.model})")
        parts.append("  => (T, Q) is Pareto-optimal within the union of "
                     "the stated models.")
        return "\n".join(parts)

    def verify(self) -> bool:
        """Cheap re-verification: algebraic facts + construction re-eval."""
        ok = True
        if self.task == "f24_inversion":
            if f24_span_lower_bound_T() != 4:
                ok = False
            r = f24_bit0_needs_many_products()
            if r != -1:  # bit 0 must NOT be reachable with <=4 products
                ok = False
            facts = f24_T5_rank_argument()
            if not facts.get("T_ge_5_for_any_Q"):
                ok = False
        return ok

    def to_json(self) -> str:
        return json.dumps(asdict(self), indent=2)

    @staticmethod
    def from_json(s: str) -> "Certificate":
        d = json.loads(s)
        d["legs"] = [Leg(**l) for l in d["legs"]]
        return Certificate(**d)


